def _rand_code(n=6):
    return "".join(random.choices(string.ascii_lowercase + string.digits, k=n))


def _phone():
    return random.choice(["08", "09", "06"]) + "".join(random.choices(string.digits, k=8))


def _scam_link():
    kind = random.random()
    if kind < 0.3:
        return f"https://bit.ly/{_rand_code(7)}"
    if kind < 0.6:
        word = random.choice(["kbank-verify", "scb-update", "th-post", "refund-tax", "pea-refund", "thaigov-help", "krungthai-secure", "parcel-th", "line-gift"])
        return f"https://{word}{random.choice(TLDS)}/{_rand_code(5)}"
    return f"www.{random.choice(['bonus', 'vip', 'win', 'easy', 'rich', 'gold'])}{random.randint(10, 999)}{random.choice(TLDS)}"


def _line_id():
    return "@" + random.choice(["support", "admin", "vip", "help", "service", "rich", "job"]) + str(random.randint(1, 999))


