def _noise(text: str) -> str:
    """ทำให้ข้อความหลากหลายขึ้นเล็กน้อย เหมือนคนพิมพ์จริง"""
    if random.random() < 0.15:
        text = text.replace(" ", "", 1)
    if random.random() < 0.1:
        text = text + random.choice(["!!", "!", "..", " ด่วน"]) if random.random() < 0.5 else text
    if random.random() < 0.08:
        text = random.choice(["[แจ้งเตือน] ", "แจ้ง: ", ""]) + text
    return text


def generate(per_template: int = 30, seed: int = 42) -> list[dict]:
    """คืน list ของ {text, label(1=หลอกลวง), category, group}"""
    random.seed(seed)
    rows = []
    for label, bank in ((1, SCAM_TEMPLATES), (0, LEGIT_TEMPLATES)):
        for category, templates in bank.items():
            for t_idx, template in enumerate(templates):
                seen = set()
                for _ in range(per_template):
                    text = _noise(template.format(**_slots())).strip()
                    if text in seen:
                        continue
                    seen.add(text)
                    rows.append({"text": text, "label": label, "category": category,
                                 "group": f"{category}/{t_idx}"})
    return rows


